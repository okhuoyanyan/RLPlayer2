// 物理节流闸（pace_budget）—— 纯函数，不打开任何音频设备（铁律 1）。
//
// 现场来源（2026-11-13，ZiSan UAC2 真机，WASAPI 独占，源=目标率）：
//   rate=1536000  8 s 素材 → 3.23 s「播完」（2.47×），缓冲 20 ms 时 0.45 s（17.9×）
//   同一素材、同一端点，缓冲 500 ms → 8.24 s（0.97×，正常）
//   rate=1411200 / 768000 同条件都是 0.97~0.98×（正常）
// 判据：DAC 只能按自己的时钟消费 rate 帧/秒，8 s 音频不可能 3.2 s 播完 ⟹ 是驱动报告的
// padding 没起节流作用，而不是设备快。pace_budget 给写入加一道与驱动无关的物理上限。
//
// 这个测试证明的是「上限本身算得对」，不能证明「真机上不再灌爆」——
// 后者由真机实测（见 docs/ZiSan-UAC2-能力核实-20261113.md）负责，两者不可互相替代。
#include "audio/wasapi_out.h"
#include <cstdio>
#include <cmath>

using rta::audio::pace_budget;
using rta::audio::clock_room;

static int gFail = 0;
static void chk(bool ok, const char* what) {
    if (!ok) { std::printf("FAIL %s\n", what); ++gFail; }
}

int main() {
    // ---- 1. 启动瞬间只能写一个缓冲，不许把整个文件灌进去 ----
    // 8 s @1536000 = 12,288,000 帧；缓冲 153600 帧。t=0 时预算应当就是 153600。
    {
        const long long b = pace_budget(0, 0.0, 1536000u, 153600u);
        chk(b == 153600, "t=0 预算应等于一个缓冲");
    }
    // ---- 2. 真实时间过去 1 s 后，最多再写 ~1 s 的帧（含 2% 容差）----
    {
        const long long b = pace_budget(153600, 1.0, 1536000u, 153600u);
        // allowed = 1*1536000*1.01 + 153600 = 1704960；budget = 1704960-153600 = 1551360
        chk(b == 1551360, "1 s 后预算 = 1.01 s 帧数");
        chk(b < 1536000 * 2, "1 s 后预算不得超过 2 s 帧数");
    }
    // ---- 3. 灌爆形态必须被闸住：0.36 s 就写了 12,288,000 帧 ----
    {
        const long long b = pace_budget(12288000, 0.36, 1536000u, 153600u);
        chk(b == 0, "灌爆形态预算必须为 0");
    }
    // ---- 4. 正常形态不许被误伤：0.97× 实时 ----
    // 8 s 素材跑 8.25 s，已写约 12,288,000 帧；此时预算应仍 > 0（不能把正常播放卡死）
    {
        const long long b = pace_budget(12288000, 8.25, 1536000u, 153600u);
        chk(b > 0, "0.97x 实时不应被闸卡死");
    }
    // ---- 5. 真实时钟略快（本机实测 100.4%）必须被 5% 容差覆盖 ----
    {
        // 8 s 内设备消费 8.032 s 的帧；我们按 1.004 倍写，预算不能变负
        const long long b = pace_budget((size_t)(1536000.0 * 8.032), 8.0, 1536000u, 153600u);
        chk(b >= 0, "100.4% 时钟偏差不应把预算打成负数");
        chk(b > 0, "100.4% 时钟偏差下仍应有可写预算");
    }
    // ---- 6. 缓冲很小（20 ms）时同样成立 ----
    {
        const long long b = pace_budget(0, 0.0, 1536000u, 30720u);
        chk(b == 30720, "20ms 缓冲 t=0 预算等于缓冲");
        const long long b2 = pace_budget(30720, 0.2, 1536000u, 30720u);
        // allowed = 0.2*1536000*1.01+30720 = 340,  0.2*1536000=307200; *1.01=310272; +30720=340992; budget=310272
        chk(b2 == 310272, "20ms 缓冲 0.2s 后预算");
    }
    // ---- 7. 参数不足时不节流（返回 -1）----
    {
        chk(pace_budget(0, 1.0, 0u, 153600u) == -1, "rate=0 应不限");
        chk(pace_budget(0, 1.0, 1536000u, 0u) == -1, "buffer=0 应不限");
        chk(pace_budget(0, NAN, 1536000u, 153600u) == -1, "elapsed=NaN 应不限");
        chk(pace_budget(0, -1.0, 1536000u, 153600u) == -1, "elapsed<0 应不限");
    }
    // ---- 8. 设备被挂起后恢复：预算可以很大（允许追赶），但不能无限 ----
    {
        const long long b = pace_budget(153600, 3.5, 1536000u, 153600u);
        chk(b > 0 && b <= (long long)(3.5 * 1536000 * 1.02) + 153600, "恢复后预算有界");
    }
    // ---- 9. 44.1k 常规档不能被误伤 ----
    {
        const long long b = pace_budget(0, 0.0, 44100u, 4410u);
        chk(b == 4410, "44.1k t=0 预算等于缓冲");
        const long long b2 = pace_budget(4410, 1.0, 44100u, 4410u);
        // allowed = 44100*1.01 + 4410 = 44541 + 4410 = 48951 ; budget = 44541
        chk(b2 == 44541, "44.1k 1s 后预算合理");
    }

    // ---- 10. 设备时钟背压（ZiSan 1536000：padding 报小了，靠"在飞帧数"兜积压）----
    // 现场：1411200 稳态 backlog 恒 141312（=1 个缓冲）；1536000 每秒涨 77,000 帧，
    // 8 s 涨到 791,880。k=2 的封顶必须能兜住"持续多写"，又不能把 1 个缓冲的正常稳态卡死。
    // 额度 = max(k×缓冲, rate×0.25s)；1536000 的 250 ms 下限 = 384000 帧，大于 2 个 100 ms 缓冲。
    {
        // 1411200 的 500 ms 下限 = 705600 帧
        chk(clock_room(141312, 141312u, 1411200u) == 705600 - 141312, "1411 稳态 1 缓冲不被卡");
        chk(clock_room(0, 153600u, 1536000u) == 768000, "空缓冲时额度 = 500 ms 下限");
        chk(clock_room(768000, 153600u, 1536000u) == 0, "在飞满额度必须停写");
        chk(clock_room(791880, 153600u, 1536000u) == 0, "1536000 现场积压形态必须停写");
        chk(clock_room(251315, 153600u, 1536000u) == 768000 - 251315, "1 s 后积压后剩余额度");
        // 小缓冲：额度由时间下限兜住，不能被 2×20ms 卡死（第二次踩坑的现场形态）
        chk(clock_room(57344, 30720u, 1536000u) > 300000, "20 ms 缓冲的额度必须远大于 2 个缓冲");
        chk(clock_room(100000, 28672u, 1411200u) > 200000, "1411/20ms 现场形态不得被判满");
        chk(clock_room(0, 0u, 1536000u) == -1, "buffer=0 应不启用");
        chk(clock_room(100, 153600u, 1536000u, 0) == -1, "k=0 应不启用");
        // 负在飞（时钟超前，例如设备刚 seek）不能变成负预算
        chk(clock_room(-5000, 153600u, 1536000u) == 768000 + 5000, "负在飞时预算放大而不是变小");
    }

    if (gFail == 0) std::printf("pace_guard OK (10 groups)\n");
    else std::printf("pace_guard FAILED %d\n", gFail);
    return gFail == 0 ? 0 : 1;
}