inline void fft(std::vector<DC> &a) {
  size_t n = a.size();
  check_design_cancel();
  if (n < 2) return;
  if (n & (n - 1)) throw std::invalid_argument("DD FFT length must be a power of two");
  for (size_t i = 1, j = 0; i < n; ++i) {
    if ((i & 4095) == 0) check_design_cancel();
    size_t b = n >> 1;
    for (; j & b; b >>= 1)
      j ^= b;
    j ^= b;
    if (i < j)
      std::swap(a[i], a[j]);
  }
  // One scratch allocation, rebuilt in the identical recurrence order per stage.
  std::vector<DC> w; w.reserve(n / 2);
  unsigned stage = 1;
  for (size_t len = 2; len <= n; len *= 2, ++stage) {
    check_design_cancel();
    w.resize(len / 2);
    w[0] = {{1, 0}, {0, 0}};
    for (size_t k = 1; k < w.size(); ++k) {
      if ((k & 4095) == 0) check_design_cancel();
      w[k] = mul(w[k - 1], roots[stage]);
    }
    for (size_t i = 0; i < n; i += len)
      for (size_t k = 0; k < len / 2; ++k) {
        if ((k & 4095) == 0) check_design_cancel();
        DC u = a[i + k], v = mul(a[i + k + len / 2], w[k]);
        a[i + k] = add(u, v);
        a[i + k + len / 2] = sub(u, v);
      }
    if (len == n) break; // Do not overflow the stage length.
  }
}

inline std::vector<double> convolve(const std::vector<double> &a,
                                    const std::vector<double> &b) {
  if (a.empty() || b.empty())
    return {};
  check_design_cancel();
  if (a.size() > std::numeric_limits<size_t>::max() - b.size())
    throw std::length_error("DD convolution support overflow");
  size_t need = a.size() + b.size() - 1, n = 1;
  if (need > (size_t(1) << (std::numeric_limits<size_t>::digits - 1)))
    throw std::length_error("DD convolution FFT size overflow");
  while (n < need)
    n *= 2;
  std::vector<DC> A(n), B(n);
  for (size_t i = 0; i < a.size(); ++i) {
    if ((i & 4095) == 0) check_design_cancel();
    A[i].r.h = a[i];
  }
  for (size_t i = 0; i < b.size(); ++i) {
    if ((i & 4095) == 0) check_design_cancel();
    B[i].r.h = b[i];
  }
  fft(A);
  fft(B);
  for (size_t i = 0; i < n; ++i) {
    if ((i & 4095) == 0) check_design_cancel();
    A[i] = mul(A[i], B[i]);
    A[i].i = neg(A[i].i);
  }
  // Product is now wholly in A. Release B before the inverse FFT scratch
  // allocation: same arithmetic and output bits, lower live allocation peak.
  std::vector<DC>().swap(B);
  fft(A);
  std::vector<double> out(need);
  for (size_t i = 0; i < need; ++i) {
    if ((i & 4095) == 0) check_design_cancel();
    out[i] = (A[i].r.h + A[i].r.l) / (double)n;
  }
  return out;
}
