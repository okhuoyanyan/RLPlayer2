// filter_cache.h — 滤波器原型的磁盘缓存（避免每次起播重算几十秒的相位变换）
//
// 背景（2026-11-01）：mp/ip 的相位变换走倒谱/级联，代价随原型长度线性增长：
//   44.1→384k 的 poly-sinc-mp 要 3.96 s、poly-sinc-long-mp / long-ip 要 8.54 / 8.56 s
//   （线性相位同尺寸只要 0.2~0.5 s）。播放路径每次新建 Pipeline 都会重算一遍，
//   用户看到的是"点了播放没反应"。
//
// 做法：把**设计出来的原型**按参数签名缓存到磁盘，命中时直接读回。
//   * 只缓存大原型（小滤波器设计是毫秒级，没必要碰盘）；
//   * 参数签名包含全部输入 + 设计版本号（改了算法必须改 kDesignEpoch，否则会读到旧系数）；
//   * 落盘用"临时文件 + 原子替换"，读到一半的文件不可能被看见；
//   * 文件自带长度与 FNV-1a 校验，损坏就当未命中（重新设计并覆盖），绝不拿坏系数去播；
//   * 环境变量 RLPLAYER_FILTER_CACHE=0 可整体关闭（复现/对照实验用）。
//
// 关键约束：缓存的是**逐位相同的原型**，不会改变任何滤波器输出。命中与未命中的系数
// 必须完全相等（tests/test_filter_cache.cpp 断言逐样本相等）。
